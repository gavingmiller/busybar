// 32 wide x 14 tall, one entry per animation frame (32 frames, looped by the
// device natively at TRAIL_FPS=16, so the loop takes 2 real seconds). The
// trail has 2 simultaneous 8px-wide "bumps" scrolling left 1px/frame; each
// bump independently alternates peaks-up/peaks-down every 2 frames (period
// 4), offset from each other by half that period so they're never in sync —
// one peaks up while the other peaks down.
//
// This is 32 frames, not 16, on purpose: with 2 bumps spaced 16px apart on a
// 32px-wide trail, one full physical lap (a bump crossing the whole 32px
// canvas) takes 32 frames, not 16. A 16-frame loop can make the *shape*
// repeat seamlessly (the two bumps are 16px apart, so after 16 frames each
// bump sits exactly where the other one started) — but since the desync
// makes the two bumps direction-wise distinguishable, folding that 32-frame
// physical cycle into 16 stored frames forced one bump's up/down parity to
// silently reassign to the other bump for one frame each half-cycle. That
// showed up on the device as a visible stutter/hold roughly every 4 frames
// (reported as "a weird pause & slide... about midway through"): confirmed
// by tracking each bump as a continuous physical run (nearest-position
// matching frame-to-frame) — the old 16-frame data held one bump's
// direction for 4 frames instead of the intended 2 right at the point where
// the mod-16 reference wrapped. Storing the true 32-frame physical period
// removes the fold entirely, so each bump's own position and direction are
// a single continuous function of tick with no reassignment anywhere,
// verified frame-by-frame with the same continuous-run tracking. Loop still
// closes seamlessly (frame 32 -> frame 0 exact match).
